package container;

import com.github.dockerjava.api.DockerClient;
import com.github.dockerjava.api.command.CreateContainerCmd;
import com.github.dockerjava.api.command.PullImageResultCallback;
import com.github.dockerjava.api.command.WaitContainerResultCallback;
import com.github.dockerjava.api.exception.NotFoundException;
import com.github.dockerjava.api.model.Bind;
import com.github.dockerjava.api.model.HostConfig;
import com.github.dockerjava.api.model.Volume;
import com.github.dockerjava.core.DefaultDockerClientConfig;
import com.github.dockerjava.core.DockerClientConfig;
import com.github.dockerjava.core.DockerClientImpl;
import com.github.dockerjava.httpclient5.ApacheDockerHttpClient;
import runserver.ProgramRunner;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Executes a Python program inside an isolated Docker container.
 * Equivalent to:
 * docker run --name run-<id> --network none --memory 256m --memory-swap 256m --user <uid>:<gid> \
 *   -v <dir>:/work python:3.12-slim \
 *   sh -c "timeout 10 python /work/prog.py < /work/input.txt > /work/out.txt 2> /work/err.txt; echo \$? > /work/exit.txt"
 */
public class ContainerExecutor implements ProgramRunner {

    private static final String IMAGE = "python";
    private static final String TAG = "3.12-slim";
    private static final long MEMORY = 256L * 1024 * 1024;
    private static final String COMMAND =
            "timeout 10 python /work/prog.py < /work/input.txt > /work/out.txt 2> /work/err.txt;"
                    + " echo $? > /work/exit.txt";

    public ContainerExecutor() {
    }

    private static void pullIfMissing(DockerClient docker, String image, String tag)
            throws InterruptedException {
        try {
            docker.inspectImageCmd(image + ":" + tag).exec();
        } catch (NotFoundException e) {
            System.out.println("Pulling " + image + ":" + tag + " ...");
            docker.pullImageCmd(image).withTag(tag)
                    .exec(new PullImageResultCallback())
                    .awaitCompletion();
        }
    }

    @Override
    public int run(String requestId, Path requestDir) throws Exception {
        // Use the directory passed as parameter
        Path dir = requestDir.toAbsolutePath().normalize();
        String containerName = "run-" + requestId;
        String containerId = null;

        // Configure the Docker client inside the method
        DockerClientConfig config = DefaultDockerClientConfig.createDefaultConfigBuilder().build();
        ApacheDockerHttpClient http = new ApacheDockerHttpClient.Builder()
                .dockerHost(config.getDockerHost())
                .sslConfig(config.getSSLConfig())
                .build();

        try (DockerClient docker = DockerClientImpl.getInstance(config, http)) {
            // Ensure the image is available before execution
            pullIfMissing(docker, IMAGE, TAG);

            // Define resource constraints (no network, 256MB RAM, /work volume)
            HostConfig hostConfig = HostConfig.newHostConfig()
                    .withNetworkMode("none")
                    .withMemory(MEMORY)
                    .withMemorySwap(MEMORY)
                    .withBinds(new Bind(dir.toString(), new Volume("/work")));

            // Create the container
            CreateContainerCmd create = docker.createContainerCmd(IMAGE + ":" + TAG)
                    .withName(containerName)
                    .withHostConfig(hostConfig)
                    .withCmd("sh", "-c", COMMAND);

            String user = currentUser();
            if (user != null) {
                create.withUser(user);
            }

            containerId = create.exec().getId();

            try {
                // Start and wait for completion
                docker.startContainerCmd(containerId).exec();
                docker.waitContainerCmd(containerId)
                        .exec(new WaitContainerResultCallback())
                        .awaitStatusCode();
            } finally {
                // Remove the container in the finally block to prevent leftovers
                if (containerId != null) {
                    try {
                        docker.removeContainerCmd(containerId).withForce(true).exec();
                    } catch (Exception e) {
                        System.err.println("Error removing container " + containerName + ": " + e.getMessage());
                    }
                }
            }
        }

        // 7. Read the exit.txt file generated by the container in /work
        Path exitFile = dir.resolve("exit.txt");
        if (!Files.exists(exitFile)) {
            throw new IllegalStateException("The exit.txt file was not generated by the container.");
        }

        return Integer.parseInt(Files.readString(exitFile).trim());
    }

    // uid:gid of the current user (Linux/macOS); null on Windows
    private static String currentUser() {
        if (System.getProperty("os.name").startsWith("Windows")) {
            return null;
        }
        com.sun.security.auth.module.UnixSystem unix = new com.sun.security.auth.module.UnixSystem();
        return unix.getUid() + ":" + unix.getGid();
    }
}